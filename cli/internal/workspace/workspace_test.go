// TestPathValidation tests workspace path validation
func TestPathValidation(t *testing.T) {
	testCases := []struct {
		name        string
		path        string
		expectError bool
		description string
	}{
		{
			name:        "valid absolute path",
			path:        "/tmp/.chauffeur",
			expectError: false,
			description: "Should accept valid absolute paths",
		},
		{
			name:        "valid relative path",
			path:        "./.chauffeur",
			expectError: false,
			description: "Should accept valid relative paths",
		},
		{
			name:        "empty path",
			path:        "",
			expectError: true,
			description: "Should reject empty paths",
		},
		{
			name:        "path with dangerous characters",
			path:        "/tmp/.chauffeur/../../../etc",
			expectError: true,
			description: "Should reject paths with directory traversal",
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			// Basic path validation
			hasPathTraversal := strings.Contains(tc.path, "..")
			isEmpty := tc.path == ""

			isInvalid := hasPathTraversal || isEmpty

			if tc.expectError && !isInvalid {
				t.Errorf("Expected path %s to be invalid", tc.path)
			}
			if !tc.expectError && isInvalid {
				t.Errorf("Expected path %s to be valid", tc.path)
			}
		})
	}
}

